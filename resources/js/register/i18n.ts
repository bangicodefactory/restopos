const REGISTER_DICTIONARIES: Record<string, Record<RegisterKey, string>> = {
    en: registerEn,
    fr: registerFr,
};

export type RegisterTranslate = (
    key: RegisterKey | SharedKey,
    params?: Record<string, string | number>,
) => string;

function interpolate(template: string, params?: Record<string, string | number>): string {
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in params ? String(params[key]) : match));
}

/**
 * The register translator. Register keys win; anything else falls through to `@shared/i18n`, so
 * `t('status.offline')` and `t('reg.pay.due')` are both legal and both type-checked.
 */
export function useT(): RegisterTranslate {
    const { locale, t } = useI18n();

    return useCallback<RegisterTranslate>(
        (key, params) => {
            const dictionary = REGISTER_DICTIONARIES[locale] ?? registerEn;
            const template = (dictionary as Record<string, string | undefined>)[key];
            if (template !== undefined) return interpolate(template, params);
            const fallback = (registerEn as Record<string, string | undefined>)[key];
            if (fallback !== undefined) return interpolate(fallback, params);
            return t(key as SharedKey, params);
        },
        [locale, t],
    );
}
